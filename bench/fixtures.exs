# Genera fixtures para benchmarks: proyectos Elixir sintéticos de varios
# tamaños. Corre una vez, cachea en bench/fixtures/.
#
# Uso:
#   mix run bench/fixtures.exs

defmodule Bench.Fixtures do
  @moduledoc """
  Build synthetic Elixir projects at three sizes for benchmarking:
    - small:  10 files,  ~50 lines each
    - medium: 100 files, ~50 lines each
    - large:  500 files, ~50 lines each

  Cached under `bench/fixtures/{small,medium,large}/`. Re-running is
  idempotent — fixtures only get created if the directory is missing.
  """

  @sizes %{
    small: 10,
    medium: 100,
    large: 500
  }

  @module_template """
  defmodule <%= mod_name %> do
    @moduledoc \"\"\"
    Module for benchmark fixture: handles <%= action %>.
    Generated by bench/fixtures.exs — not real code.
    \"\"\"

    alias <%= dep_module %>

    @doc \"Public function that orchestrates <%= action %>.\"
    def <%= fun_name %>(input) when is_binary(input) do
      meta = %{id: input, action: :<%= action %>}
      Dep.validate(meta)
      do_<%= action %>(input)
    end

    defp do_<%= action %>(input) do
      result = String.upcase(input)
      {:ok, %{input: input, result: result, ts: System.system_time()}}
    end

    defdelegate child_call(x), to: <%= dep_module %>, as: <%= dep_fun %>

    @doc \"Private helper: returns a tuple.\"
    defp helper(x), do: {x, :ok}
  end
  """

  @dep_template """
  defmodule <%= mod_name %> do
    def validate(%{action: _}), do: :ok
    def <%= fun %>(x), do: {:ok, x}
  end
  """

  def build_all(base \\ "bench/fixtures") do
    for {size, count} <- @sizes do
      dir = Path.join(base, "#{size}")
      File.rm_rf!(dir)
      File.mkdir_p!(Path.join(dir, "lib"))
      IO.puts("Building #{size} (#{count} files)...")
      build(dir, count)
    end
    IO.puts("Done.")
  end

  # Build a single Elixir file with `line_count` lines of a deterministic
  # module structure. Used by the large-file and unicode benchmarks.
  def build_file(path, opts) do
    line_count = Keyword.get(opts, :line_count, 100)
    module = Path.basename(path, ".ex") |> Macro.camelize()

    body =
      Enum.map_join(1..line_count, "\n", fn i ->
        "  def f#{i}(x), do: x + #{i}"
      end)

    content = "defmodule #{module} do\n#{body}\nend\n"
    File.write!(path, content)
    path
  end

  defp build(dir, count) do
    for i <- 1..count do
      mod = "Mod#{i}"
      fun = "process_#{i}"
      dep_mod = "Dep#{rem(i, 10) + 1}"
      dep_fun = "transform_#{rem(i, 5) + 1}"
      action = "act#{rem(i, 7) + 1}"

      dep_content =
        EEx.eval_string(@dep_template,
          mod_name: dep_mod,
          fun: dep_fun,
          assigns: []
        )

      content =
        EEx.eval_string(@module_template,
          mod_name: mod,
          fun_name: fun,
          action: action,
          dep_module: dep_mod,
          dep_fun: dep_fun,
          assigns: []
        )

      # One Dep per 10 modules
      if rem(i, 10) == 1 do
        File.write!(Path.join(dir, "lib/#{dep_mod}.ex"), dep_content)
      end

      File.write!(Path.join(dir, "lib/#{mod}.ex"), content)
    end

    # mix.exs so it looks like a real project
    File.write!(
      Path.join(dir, "mix.exs"),
      """
      defmodule Fixture.MixProject do
        use Mix.Project

        def project, do: [app: :fixture, version: "0.1.0"]
        def application, do: [extra_applications: [:logger]]
      end
      """
    )
  end
end

Bench.Fixtures.build_all()
